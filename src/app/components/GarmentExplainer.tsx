// ─── Polygon helper ────────────────────────────────────────────────────────────

function poly(nums: number[]): string {
  const pts: string[] = [];
  for (let i = 0; i + 1 < nums.length; i += 2)
    pts.push(`${nums[i]},${nums[i + 1]}`);
  return pts.join(" ");
}

